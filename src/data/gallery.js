export function getPublishedGalleryPhotos() {
  return galleryPhotos.filter(
    (photo) => photo.isPublished && !photo.privacyReviewRequired
  );
}

export function getFeaturedGalleryPhotos(limit = 6) {
  return galleryPhotos
    .filter(
      (photo) =>
        photo.isPublished && photo.featured && !photo.privacyReviewRequired
    )
    .slice(0, limit);
}

export function getGalleryPhotosByCategory(category) {
  if (!category || category === "all") {
    return getPublishedGalleryPhotos();
  }

  return galleryPhotos.filter(
    (photo) =>
      photo.isPublished &&
      !photo.privacyReviewRequired &&
      photo.category === category
  );
}

export function getGalleryPhotoBySlug(slug) {
  return galleryPhotos.find(
    (photo) => photo.slug === slug
  );
}

export default galleryPhotos;
